import { createGlowColors, tokens } from './palette.js';

// Dense neon halos, restrained constant/electric shadows, and unlit strings.
// Foregrounds remain Ectoplasm's.
export function createGlowStyles(palette = tokens) {
  const colors = createGlowColors(palette);
  const neutral = ['textPrimary', 'textSecondary', 'textMuted'].map((key) => palette[key].toLowerCase());
  const styles = {};
  for (const [name, color] of Object.entries(colors)) {
    const foreground = color.foreground.toLowerCase();
    if (neutral.includes(foreground) || styles[foreground]) {
      throw new Error(`Glow color ${name} must be distinct from neutral text and other glow colors`);
    }
    const { outline: o, halo: h } = color;
    const shadows = {
      synGlow:      `0 0 2px ${o}, 0 0 6px ${h}FF, 0 0 12px ${h}CC, 0 0 20px ${h}88`,
      synKeyword:   `0 0 2px ${o}, 0 0 5px ${h}CC, 0 0 6px ${h}AA, 0 0 14px ${h}66`,
      synConstant:  `0 0 2px ${o}, 0 0 8px ${h}AA, 0 0 2px ${h}88`,
      synVariable: `0 0 2px ${o}, 0 0 8px ${h}72, 0 0 2px ${h}72`,
    };
    styles[foreground] = shadows[name];
  }
  return styles;
}

// Serialized by the build. Runs only in the workbench renderer, never in the
// extension host. Do not depend on module-scoped variables inside this function.
function installGlow(config) {
  const key = '__ectoplasmSyntaxGlow';
  if (window[key]) window[key]();
  const style = document.createElement('style');
  style.id = 'ectoplasm-syntax-glow';
  document.head.appendChild(style);
  let tokensElement;
  let frame;

  function refresh() {
    frame = undefined;
    if (!style.isConnected) document.head.appendChild(style);
    const rules = [];
    // The theme class is generated by VS Code from publisher/name/theme path.
    // CSS scoping also makes a theme switch take effect before observers run.
    if (document.querySelector(config.scope)) {
      // Attach to Monaco's cursor so native movement, visibility, and blinking
      // apply to the halo too. Foreground remains editorCursor.foreground.
      const a = config.electric;
      rules.push(`${config.scope} .monaco-editor .cursors-layer > .cursor { box-shadow: 0 0 3px 1px ${a}, 0 0 8px 2px ${a}CC, 0 0 16px 4px ${a}88, 0 0 28px 6px ${a}44; }`);
      for (const rule of tokensElement?.sheet?.cssRules || []) {
        const raw = rule.style?.getPropertyValue('color').trim().toLowerCase();
        if (!raw) continue;
        const rgb = raw.match(/^rgb\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\)$/);
        const color = rgb
          ? `#${rgb.slice(1).map((channel) => Number(channel).toString(16).padStart(2, '0')).join('')}`
          : raw;
        const shadow = config.styles[color];
        if (!shadow) continue;
        for (const selector of (rule.selectorText || '').split(',')) {
          // Discover current token numbers; never copy hardcoded .mtkN IDs.
          if (!/^\.mtk\d+$/.test(selector.trim())) continue;
          // VS Code may wrap tokens in an additional span inside each line.
          rules.push(`${config.scope} .monaco-editor .view-lines .view-line span${selector.trim()} { text-shadow: ${shadow}; backface-visibility: hidden; }`);
        }
      }
    }
    const css = rules.join('\n');
    if (style.textContent !== css) style.textContent = css;
  }

  const schedule = () => {
    if (frame === undefined) frame = requestAnimationFrame(refresh);
  };
  const tokenObserver = new MutationObserver(schedule);
  function findTokens() {
    const next = document.querySelector('style.vscode-tokens-styles');
    if (next === tokensElement) return;
    tokenObserver.disconnect();
    tokensElement = next;
    if (next) tokenObserver.observe(next, { childList: true, characterData: true, subtree: true });
    schedule();
  }
  const discoveryObserver = new MutationObserver((changes) => {
    // Avoid parsing token rules on every edit, scroll, or cursor movement.
    // Rebind when a theme refresh replaces either source node, and restore our
    // style if it (or its containing head) was removed.
    const sources = 'style.vscode-tokens-styles, .monaco-workbench';
    if (changes.some((change) => [...change.addedNodes, ...change.removedNodes].some((node) =>
      node.nodeType === 1 && (node.contains(style) || node.matches(sources) || node.querySelector(sources))))) {
      findTokens();
      watchTheme();
      schedule();
    }
  });
  discoveryObserver.observe(document.documentElement, { childList: true, subtree: true });
  const themeObserver = new MutationObserver(schedule);
  // Theme classes live on the workbench container. Observe class changes only
  // on that container; discovery above also handles late startup/replacement.
  let workbench;
  const watchTheme = () => {
    const next = document.querySelector('.monaco-workbench');
    if (next === workbench) return;
    workbench = next;
    themeObserver.disconnect();
    if (next) themeObserver.observe(next, { attributes: true, attributeFilter: ['class'] });
    schedule();
  };
  watchTheme();
  findTokens();
  schedule();
  window[key] = () => {
    tokenObserver.disconnect();
    discoveryObserver.disconnect();
    themeObserver.disconnect();
    if (frame !== undefined) cancelAnimationFrame(frame);
    style.remove();
    delete window[key];
  };
}

export function createGlowScript(manifest) {
  const themePath = manifest.contributes.themes[0].path.replace(/^\.\//, '');
  const themeClass = `${manifest.publisher}.${manifest.name}-${themePath}`.replace(/[^_a-zA-Z0-9-]/g, '-');
  const config = { scope: `.monaco-workbench.${themeClass}`, electric: tokens.electric, styles: createGlowStyles() };
  return `// Ectoplasm syntax glow: managed workbench script\n(${installGlow.toString()})(${JSON.stringify(config, null, 2)});\n`;
}
